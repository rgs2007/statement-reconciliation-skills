#!/usr/bin/env python3
"""Generate the self-contained test prompt from the committed fixture.

The path-based prompts in docs/TESTING_THE_SKILL.md only resolve inside a
repository clone. Skills are normally installed to ~/.claude/skills/ and used
from whatever project you happen to be in, where `tests/fixtures/...` does not
exist — and an installed skill carries no CSVs. So the most portable test is
one that carries its data inline.

This generator keeps that prompt honest: the embedded CSVs are read from the
real fixture, so the prompt cannot drift away from the figures it is graded
against. A test regenerates and compares.

    python tools/make_test_prompt.py            # write the prompt
    python tools/make_test_prompt.py --check    # fail if stale
"""
from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXTURE = os.path.join(ROOT, "tests", "fixtures", "02-faults")
OUT = "docs/test-prompt-selfcontained.md"


def read(name: str) -> str:
    with open(os.path.join(FIXTURE, "sources", name), encoding="utf-8") as fh:
        return fh.read().strip()


def build() -> str:
    metrics = json.load(open(os.path.join(FIXTURE, "expected", "metrics.json")))
    opening, closing, movements = (read("opening.csv"), read("closing.csv"),
                                   read("movements.csv"))
    rows = sum(len(x.splitlines()) - 1 for x in (opening, closing, movements))

    return f"""<!-- GENERATED FILE — DO NOT EDIT.
     Source: tests/fixtures/02-faults/
     Regenerate: python tools/make_test_prompt.py
     The embedded data is read from the fixture, so it cannot drift away from
     the figures below. A test regenerates and compares. -->

# Self-contained test prompt — no clone required

The prompts in [`TESTING_THE_SKILL.md`](TESTING_THE_SKILL.md) use paths like
`tests/fixtures/02-faults/sources/`, which only resolve **inside a clone of
this repository**. Skills are normally installed to `~/.claude/skills/` and
used from whatever project you are in, and an installed skill carries no test
data — so those prompts fail with "file not found" anywhere else.

This prompt carries its data inline. It works in any session: Claude Code in
any directory, claude.ai, Copilot Chat, Cursor, or a tool with no filesystem
at all.

Paste everything in the box below as a single message.

The data is given to the skill rather than generated by it, which keeps the
test blind — a model that invented the defects would already know the answers.

---

## The prompt (EN)

> I need help reconciling an accounts-payable ledger that doesn't tie out.
> Three extracts for the same period are below: the opening balances, the
> closing balances, and every posting in between. The closing balances should
> follow from the opening ones plus the period's activity, but they don't, and
> I can't see why.
>
> Save each block to a file and work out what is wrong with the data. I need to
> know the cause of each difference, how confident you are in it, and what I
> should do about it.
>
> **opening.csv**
> ```csv
> {opening.replace(chr(10), chr(10) + "> ")}
> ```
>
> **closing.csv**
> ```csv
> {closing.replace(chr(10), chr(10) + "> ")}
> ```
>
> **movements.csv**
> ```csv
> {movements.replace(chr(10), chr(10) + "> ")}
> ```

## O prompt (PT)

> Preciso de ajuda para conciliar um razão de contas a pagar que não está
> fechando. Abaixo estão três extrações do mesmo período: os saldos iniciais,
> os saldos finais e todos os lançamentos entre eles. Os saldos finais
> deveriam resultar dos iniciais mais a movimentação do período, mas não
> batem, e não consigo identificar o motivo.
>
> Salve cada bloco em um arquivo e descubra o que está errado nos dados.
> Preciso saber a causa de cada diferença, o seu nível de confiança em cada
> uma e o que eu devo fazer a respeito.
>
> **opening.csv**
> ```csv
> {opening.replace(chr(10), chr(10) + "> ")}
> ```
>
> **closing.csv**
> ```csv
> {closing.replace(chr(10), chr(10) + "> ")}
> ```
>
> **movements.csv**
> ```csv
> {movements.replace(chr(10), chr(10) + "> ")}
> ```

Neither version says the amounts use comma decimals, nor that the account code
sits at the head of each description. That is deliberate: the skill has to
discover both. It can — `detect_style` infers the convention from the data,
and a run that is told nothing produces the same figures as one that is.

---

## Correct answer ({rows} data rows, 12 accounts)

| Account | Difference | Cause |
|---|---:|---|
| `6652-4` | −1,944,943.11 | `DECIMAL_SHIFT` — one posting keyed 1000× too large (1,946,890.00 should be 1,946.89) |
| `8241-1` | −37,394.41 | `DUPLICATE_POSTING` — `mv_00_0` and `mv_DUP` are the same posting |
| `8722-1` | +8,006.67 | `MISSING_MOVEMENTS` — the balance moved, no posting explains it |
| `4363-1` | +797.88 | `SUBACCOUNT_MISATTRIBUTION` — offsets its sibling exactly |
| `4363-2` | −797.88 | same pair; reclassification only, no cash impact |

- **{metrics['reconciled']} of {metrics['keys_total']} accounts reconciled**
- gross gap **{metrics['gap_gross']:,.2f}**, net **{metrics['gap_net']:,.2f}** — report both
- parent-level gross **{metrics['gap_gross_at_parent']:,.2f}**, so {metrics['gap_gross'] - metrics['gap_gross_at_parent']:,.2f} of the gross is misposting rather than missing value
- attribution **{metrics['attribution_rate_pct']}%** — one row, `mv_ORPHAN` (12,345.67), has no derivable account and should come back as an open question
- a reversal pair on `5690-01`, **{metrics['reversal_gross']:,.2f}** gross, which is *activity, not a gap*
- the equation is `closing = opening + movements`, and it should say it established that empirically

## Grading checklist

- [ ] It triggered without being told which skill to use
- [ ] It worked out the comma decimals and the embedded account code unprompted
- [ ] It solved the sign convention from the data rather than assuming it
- [ ] All five defects found
- [ ] The sibling pair reported **as a pair**, with the parent-level net — separately it overstates the problem twice
- [ ] The reversal pair reported as activity, not folded into the gap
- [ ] Net and gross separated
- [ ] `mv_ORPHAN` raised as an open question, not guessed at or dropped
- [ ] Each finding carries evidence, rationale, alternatives, confidence and a remediation step
- [ ] On the PT run: narrative in Portuguese, codes (`DECIMAL_SHIFT`, `HIGH`/`MEDIUM`/`LOW`) left in English, with a glossary — and identical figures

Finding the 1.9M decimal shift is easy; it dominates everything. Finding the
797.88 sibling pair and calling it a reclassification with no cash impact is
the real test.
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    body = build()
    p = os.path.join(ROOT, OUT)

    if a.check:
        if not os.path.exists(p):
            print(f"MISSING {OUT}\nRun: python tools/make_test_prompt.py")
            sys.exit(1)
        if open(p, encoding="utf-8").read() != body:
            print(f"STALE {OUT} — the fixture changed but the prompt was not "
                  f"regenerated, so its embedded data no longer matches the "
                  f"figures it is graded against.\n"
                  f"Run: python tools/make_test_prompt.py")
            sys.exit(1)
        print(f"up to date · {OUT} matches the fixture")
        return

    os.makedirs(os.path.dirname(p), exist_ok=True)
    changed = not os.path.exists(p) or open(p, encoding="utf-8").read() != body
    open(p, "w", encoding="utf-8").write(body)
    print(f"{'wrote' if changed else 'unchanged'} {OUT}")


if __name__ == "__main__":
    main()
